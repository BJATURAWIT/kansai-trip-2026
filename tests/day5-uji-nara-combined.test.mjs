test('Rainy and relaxed variants keep coherent routes and confirmed next-day trains',()=>{
 const rainy=normalizePreferences({dayPlans:{5:'rainy'}}),relaxed=normalizePreferences({dayPlans:{5:'relaxed'}});
 const wet=resolvedSchedule(5,rainy),slow=resolvedSchedule(5,relaxed);
 assert.ok(wet.some(x=>x.title.includes('Namba Parks')));
 assert.ok(!wet.some(x=>x.title.includes('Byodo-in')));
 assert.ok(!foodStopsForDay(5,rainy).some(x=>x.id==='nakamuraUji'));
 assert.ok(slow.some(x=>x.title.includes('Byodo-in')));
 assert.ok(slow.some(x=>x.title.includes('Todai-ji')));
 assert.ok(!slow.some(x=>x.title.includes('Kasuga')));
 assert.ok(!detailedRouteGuide(5,relaxed).legs.some(x=>x.to==='Kasuga Taisha Nara'));
 assert.ok(itinerary[5].schedule.some(x=>String(x.title).includes('Kounotori 5')));
 assert.ok(itinerary[6].schedule.some(x=>String(x.title).includes('Kounotori 22')));
});
