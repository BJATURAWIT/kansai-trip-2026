const prefs=normalizePreferences({});
test('Day 5 Nov 21 prioritizes Byodo-in and Uji matcha before Nara deer and Todai-ji',()=>{
 const d=resolveDay(5,prefs),s=d.schedule,at=t=>s.findIndex(x=>x.title.includes(t));
 assert.equal(d.date,'21 NOV');assert.equal(d.dow,'SAT');assert.match(d.location,/UJI \/ NARA/);
 for(const t of ['Byodo-in','Uji Bridge','Nakamura Tokichi','JR Uji → JR Nara','Kamaiki','Nara Park','Todai-ji','Kasuga Taisha','JR Nara → Tennoji'])assert.ok(at(t)>=0,'missing '+t);
 assert.ok(at('Byodo-in')<at('Uji Bridge'));
 assert.ok(at('Uji Bridge')<at('Nakamura Tokichi'));
 assert.ok(at('Nakamura Tokichi')<at('JR Uji → JR Nara'));
 assert.ok(at('JR Uji → JR Nara')<at('Kamaiki'));
 assert.ok(at('Kamaiki')<at('Nara Park'));
 assert.ok(at('Nara Park')<at('Todai-ji'));
 assert.ok(at('Todai-ji')<at('Kasuga Taisha'));
 assert.equal(s.find(x=>x.title.includes('Byodo-in ·')).time,'08:55–09:55');
 assert.match(s.find(x=>x.title.includes('Byodo-in ·')).detail,/¥700/);
 assert.match(s.find(x=>x.title.includes('Todai-ji Great')).detail,/¥800/);
 assert.match(d.note,/Kasuga/);
});
test('Day 5 original all intercity journeys use purchased JR pass and two individually paid metro trips',()=>{
 const s=resolvedSegments(5,prefs),f=fareSummary(5,s,defaultTickets);
 assert.equal(s.filter(x=>x.type==='jr').length,3);
 assert.equal(s.filter(x=>x.type==='metro').length,2);
 assert.ok(!s.some(x=>x.type==='kintetsu'));
 assert.equal(f.unresolved,0);
 assert.equal(f.twoPeopleYen,860);
 const guide=detailedRouteGuide(5,prefs);
 for(const station of ['JR Uji','JR Nara','JR Tennoji','Byodo-in','Uji Bridge','Nakamura Tokichi','Kamaiki','Nara Park','Todai-ji','Kasuga'])assert.ok(guide.legs.some(x=>x.to.includes(station)),'missing guide '+station);
 assert.ok(!guide.legs.some(x=>x.mode.includes('Kintetsu')));
});
test('Day 5 walk-in food includes Nakamura real photo and Kamaiki primary, Saizeriya backup',()=>{
 const stops=foodStopsForDay(5,prefs);
 assert.ok(validateFoodPlan(5,prefs));
 assert.deepEqual(stops.filter(x=>x.kind==='lunch').map(x=>[x.id,x.role]),[['kamaiki','primary'],['saizeriya','backup']]);
 assert.ok(stops.some(x=>x.id==='nakamuraUji'&&x.time==='10:20'));
 assert.equal(foodVenues.nakamuraUji.image.src,'/photos/day-5-6.jpg');
 assert.equal(foodVenues.nakamuraUji.reservation,'not-booked');
 assert.ok(!resolvedSchedule(5,prefs).some(x=>x.foodId==='nakamuraUji'));
});
